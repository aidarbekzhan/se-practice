def main():
    parser = argparse.ArgumentParser(description="Structural checker for SIS #01 report.md")
    parser.add_argument("--json", action="store_true", help="machine-readable output")
    parser.add_argument("--file", default=REPORT, help="path to report.md (default: ./report.md)")
    args = parser.parse_args()

    if args.file == REPORT and not os.path.isdir("tests") and not os.path.exists(REPORT):
        msg = "run this from inside your sis-01/ folder:  cd sis-01 && python tests/check_report.py"
        print(json.dumps({"ok": False, "error": msg}) if args.json else "ERROR: " + msg)
        return 3

    if not os.path.exists(args.file):
        res, measured, code = all_error(f"{args.file} not found"), {}, 2
    else:
        text = open(args.file, encoding="utf-8", errors="replace").read()
        res, measured = check(text)
        c = res.counts()
        code = 0 if c["FAIL"] == 0 and c["ERROR"] == 0 else 1

    c = res.counts()
    if args.json:
        print(json.dumps({"ok": code == 0, "counts": c, "total": sum(c.values()),
                          "rows": res.rows, "measured": measured}, ensure_ascii=False, indent=2))
    else:
        print_human(res, args.file)
    return code


if __name__ == "__main__":
    sys.exit(main())
